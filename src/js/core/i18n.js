    function detectInitialLang() {
        try {
            const pathname = (typeof window !== 'undefined' && window.location && window.location.pathname) || '';
            const pathMatch = pathname.match(/^\/(ar|de|es|fr|hi|ja|pt|ru|zh)(?:\/|$)/i);
            if (pathMatch) {
                const pathLang = pathMatch[1].toLowerCase();
                if (I18N[pathLang]) return pathLang;
            }
        } catch (e) {}

        try {
            const htmlLang = (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang || '').trim().toLowerCase();
            if (htmlLang && htmlLang !== 'en' && I18N[htmlLang]) {
                return htmlLang;
            }
        } catch (e) {}

        try {
            if (typeof localStorage !== 'undefined') {
                const savedLang = localStorage.getItem('app_lang');
                if (savedLang && I18N[savedLang]) return savedLang;
            }
        } catch (e) {}

        return 'en';
    }

